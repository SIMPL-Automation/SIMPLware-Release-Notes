#!/usr/bin/env python3
"""Regenerate docs/js/initiatives.js: the ticket tags in docs/*.md that are ADO Initiatives.

The site can't ask ADO which tickets are initiatives when a page loads, so this list
is kept in the repo. Run it after adding or changing ticket tags (needs `az` signed in).
Usage: python3 scripts/update-initiatives.py
"""
import glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORG = 'https://dev.azure.com/SimplAutomation'
BATCH_SIZE = 200  # az boards query handles IN lists of this size comfortably

ids = set()
for path in glob.glob(os.path.join(ROOT, 'docs', '*.md')):
    with open(path, encoding='utf-8') as f:
        ids.update(int(n) for n in re.findall(r'\[#(\d+)\]', f.read()))

initiatives = set()
ordered = sorted(ids)
for start in range(0, len(ordered), BATCH_SIZE):
    batch = ordered[start:start + BATCH_SIZE]
    wiql = ("SELECT [System.Id],[System.WorkItemType] FROM WorkItems WHERE [System.Id] IN ("
            + ','.join(map(str, batch)) + ") AND [System.WorkItemType] = 'Initiative'")
    result = subprocess.run(['az', 'boards', 'query', '--org', ORG, '--wiql', wiql, '-o', 'json'],
                            capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit('ADO query failed; initiatives.js left unchanged:\n' + result.stderr)
    initiatives.update(item['id'] for item in json.loads(result.stdout or '[]'))

out = os.path.join(ROOT, 'docs', 'js', 'initiatives.js')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/update-initiatives.py; do not edit by hand.\n')
    f.write('// Ticket tags that are ADO Initiatives, drawn in purple.\n')
    f.write('window.SIMPL_INITIATIVES = ' + json.dumps(sorted(initiatives)) + ';\n')
print(f'{len(initiatives)} initiatives out of {len(ids)} tagged tickets -> {out}')
